#!/usr/bin/env python3
"""
Converts a .tflite file into a C header (model_data.h) for TFLM.
The resulting array is what the ESP32-C3 firmware links against.
"""
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
TFLITE_PATH = REPO_ROOT / "models" / "tflite" / "v3_float.tflite"
OUTPUT_PATH = REPO_ROOT / "src" / "inference" / "include" / "model_data.h"

def main():
    # Read the TFLite file as raw bytes
    data = TFLITE_PATH.read_bytes()

    # Write a C header with the byte array + its length
    with open(OUTPUT_PATH, "w") as f:
        f.write("// Auto-generated by generate_model_header.py — do not edit.\n")
        f.write("#ifndef MODEL_DATA_H\n")
        f.write("#define MODEL_DATA_H\n\n")
        f.write("#include <cstdint>\n\n")
        f.write(f"// Model size: {len(data)} bytes\n")
        f.write("alignas(16) const unsigned char model_data[] = {\n")

        # Emit bytes 12 per line for readability
        for i in range(0, len(data), 12):
            chunk = data[i : i + 12]
            line = ", ".join(f"0x{b:02x}" for b in chunk)
            f.write(f"  {line},\n")

        f.write("};\n\n")
        f.write(f"const unsigned int model_data_len = {len(data)};\n\n")
        f.write("#endif  // MODEL_DATA_H\n")

    print(f"Wrote {OUTPUT_PATH} ({len(data)} bytes)")

if __name__ == "__main__":
    main()